#!/usr/bin/env python3
"""(not)AI Time mark: the interval brackets with clock hands at about 12:08 (a light check mark that still reads as a clock).

Writes the launcher foreground/monochrome layers, the status-bar icon and the shortcut icon:
  python3 scripts/app_icon.py            write res/drawable files
  python3 scripts/app_icon.py --preview out.png   adaptive-icon masks at several sizes (needs cairosvg)
"""
import argparse, math, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res/drawable"

# Geometry on the 108-unit adaptive-icon grid (safe zone: 66-unit circle).
WIDEN = 6.0                      # brackets moved apart from the original 43.7/64.3 tips
TOP, BOTTOM = 33.5, 74.5
TIP_L, BULGE_L = 43.7 - WIDEN, 37.8 - WIDEN
TIP_R, BULGE_R = 64.3 + WIDEN, 70.2 + WIDEN
PIVOT = (54.0, 56.0)             # slightly below centre: the hands point up, the mass stays centred
HOUR = (4.0, 11.0)               # degrees from 12, length
MINUTE = (45.0, 16.5)            # about 12:08
BRACKET_W, HAND_W, PIVOT_R = 3.4, 3.0, 3.3
INK, AMBER = "#ECEAE4", "#FFB23C"


def bracket(tip, bulge, scale=1.0, dx=0.0, dy=0.0):
    k = (BOTTOM - TOP) * 0.27
    pts = [(tip, TOP), (bulge, TOP + k), (bulge, BOTTOM - k), (tip, BOTTOM)]
    p = [f"{x * scale + dx:.2f},{y * scale + dy:.2f}" for x, y in pts]
    return f"M{p[0]} C{p[1]} {p[2]} {p[3]}"


def hands(scale=1.0, dx=0.0, dy=0.0):
    cx, cy = PIVOT
    out = []
    for angle, length in (HOUR, MINUTE):
        a = math.radians(angle)
        x, y = cx + length * math.sin(a), cy - length * math.cos(a)
        out.append(f"M{cx * scale + dx:.2f},{cy * scale + dy:.2f} L{x * scale + dx:.2f},{y * scale + dy:.2f}")
    return " ".join(out)


def dot(scale=1.0, dx=0.0, dy=0.0, r=PIVOT_R):
    cx, cy = PIVOT[0] * scale + dx, PIVOT[1] * scale + dy
    r *= scale
    return f"M{cx - r:.2f},{cy:.2f} a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0 a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0z"


def stroke(color, width, data):
    return (f'    <path android:strokeColor="{color}" android:strokeWidth="{width:g}" android:strokeLineCap="round" '
            f'android:strokeLineJoin="round" android:fillColor="#00000000"\n        android:pathData="{data}" />')


def fill(color, data):
    return f'    <path android:fillColor="{color}" android:pathData="{data}" />'


def vector(size, viewport, body, comment):
    return (f"<!-- Generated by scripts/app_icon.py. {comment} -->\n"
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{size}dp" android:height="{size}dp" '
            f'android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n' + "\n".join(body) + "\n</vector>\n")


def write():
    brackets = bracket(TIP_L, BULGE_L) + " " + bracket(TIP_R, BULGE_R)
    (RES / "ic_launcher_foreground.xml").write_text(vector(108, 108, [
        stroke(INK, BRACKET_W, brackets), stroke(AMBER, HAND_W, hands()), fill(AMBER, dot())],
        "Launcher colour layer: brackets with clock hands at about 12:08."), encoding="utf-8")
    (RES / "ic_launcher_monochrome.xml").write_text(vector(108, 108, [
        stroke("#FFFFFF", BRACKET_W, brackets), stroke("#FFFFFF", HAND_W, hands()), fill("#FFFFFF", dot())],
        "Themed-icon layer (Android 13+)."), encoding="utf-8")
    # Status bar: the mark fills the 24 grid; heavier strokes, white as the platform requires.
    s = 18.5 / (BOTTOM - TOP); dx = 12 - 54 * s; dy = 12 - 54 * s
    small = bracket(TIP_L, BULGE_L, s, dx, dy) + " " + bracket(TIP_R, BULGE_R, s, dx, dy)
    (RES / "ic_stat_notai.xml").write_text(vector(24, 24, [
        stroke("#FFFFFFFF", 2.0, small + " " + hands(s, dx, dy)), fill("#FFFFFFFF", dot(s, dx, dy, 3.0))],
        "Status-bar mark."), encoding="utf-8")
    # Shortcut: the mark on its dark disc.
    s2 = s * 0.62; dx2 = 12 - 54 * s2; dy2 = 12 - 54 * s2
    disc = "M0,12a12,12 0 1,0 24,0a12,12 0 1,0 -24,0z"
    (RES / "ic_shortcut.xml").write_text(vector(24, 24, [
        fill("#FF1D2024", disc), stroke("#FFECEAE4", 1.3, bracket(TIP_L, BULGE_L, s2, dx2, dy2) + " " + bracket(TIP_R, BULGE_R, s2, dx2, dy2)),
        stroke("#FFFFB23C", 1.3, hands(s2, dx2, dy2)), fill("#FFFFB23C", dot(s2, dx2, dy2, 2.6))],
        "Launcher shortcut: the mark on its dark disc."), encoding="utf-8")


def preview(out):
    import cairosvg, io
    from PIL import Image, ImageDraw
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108"><rect width="108" height="108" fill="#1D2024"/>'
           f'<path d="{bracket(TIP_L, BULGE_L)} {bracket(TIP_R, BULGE_R)}" stroke="{INK}" stroke-width="{BRACKET_W}" stroke-linecap="round" fill="none"/>'
           f'<path d="{hands()}" stroke="{AMBER}" stroke-width="{HAND_W}" stroke-linecap="round" fill="none"/>'
           f'<path d="{dot()}" fill="{AMBER}"/></svg>')
    img = Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg.encode(), output_width=432, output_height=432))).convert("RGBA")
    sheet = Image.new("RGB", (760, 340), (242, 243, 239))
    for (kind, size, x, y) in [("circle", 240, 30, 50), ("square", 240, 300, 50), ("circle", 96, 570, 50), ("square", 96, 570, 170), ("circle", 48, 690, 50)]:
        m = Image.new("L", (432, 432), 0); d = ImageDraw.Draw(m); inset = 72
        if kind == "circle": d.ellipse([inset, inset, 432 - inset, 432 - inset], fill=255)
        else: d.rounded_rectangle([inset, inset, 432 - inset, 432 - inset], radius=74, fill=255)
        o = Image.new("RGBA", (432, 432), (0, 0, 0, 0)); o.paste(img, (0, 0), m)
        o = o.crop((inset, inset, 432 - inset, 432 - inset)).resize((size, size), Image.LANCZOS)
        sheet.paste(o, (x, y), o)
    sheet.save(out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", type=pathlib.Path)
    a = ap.parse_args()
    if a.preview: preview(a.preview)
    else: write()
